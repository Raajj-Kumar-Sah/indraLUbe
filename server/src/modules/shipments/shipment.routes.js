import {Router} from "express";
import rateLimit from "express-rate-limit";
import {authenticate} from "../../middleware/authenticate.js";
import {authorize} from "../../middleware/authorize.js";
import * as controller from "./shipment.controller.js";
export const adminShipmentRoutes=Router();
adminShipmentRoutes.use(authenticate,authorize("ADMIN","SUPER_ADMIN"));
adminShipmentRoutes.get("/",controller.adminList);
adminShipmentRoutes.post("/:orderId",controller.create);
adminShipmentRoutes.patch("/:orderId/status",controller.adminStatus);
export const distributorShipmentRoutes=Router();
distributorShipmentRoutes.use(authenticate,authorize("DISTRIBUTOR"));
distributorShipmentRoutes.get("/",controller.mine);
distributorShipmentRoutes.get("/:orderId",controller.mineDetail);
distributorShipmentRoutes.post("/:orderId/confirm-delivery",rateLimit({windowMs:15*60*1000,limit:8,standardHeaders:"draft-7",legacyHeaders:false}),controller.confirm);
